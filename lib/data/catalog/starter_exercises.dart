/// The exercise library that ships with the app.
///
/// Lifted out of `AppDatabase` for the same reasons as the food catalog, and
/// with the same three consequences:
///
///  * `test/regression/exercise_audit_test.dart` audits every row and, more
///    importantly, the *coverage* the rows add up to. A library can be
///    perfectly well-formed and still be unable to program a session.
///  * Ids are permanent. Logged sets reference an exercise by id, so an id
///    must never be reused. Append, never renumber. (Id 55 is deliberately
///    absent -- it was never shipped, and closing the gap would renumber.)
///  * New rows reach users who already have the app, via the same high-water
///    mark the food catalog uses (`AppDatabase._mergeNewSeededRows`).
///
/// ## What the coverage invariants are, and why
///
/// The audit does not just check that fields are populated. It checks the
/// three things that make the library *usable*, each of which was violated
/// when it was written:
///
///  * **Every muscle is trainable with no equipment.** There were zero
///    bodyweight hamstring, shoulder and biceps exercises, so a user who owns
///    nothing simply could not train those.
///  * **Every movement pattern has options.** `carry` had none at all, so a
///    generated plan could never include one.
///  * **Every body part has at least five rehab options with no equipment.**
///    `WorkoutTemplateGenerator` asks for five and *silently skips the
///    session* if the pool is empty, so a shoulder-injured user with no bands
///    got a two-exercise physiotherapy session, and an ankle-injured one could
///    never get five however well equipped.
///
/// ## Contraindicated vs rehab
///
/// These are separate axes and must not be confused: being safe with a bad
/// shoulder is not the same as rehabilitating one. The audit enforces that no
/// exercise is ever both -- claiming to rehabilitate a joint it is also unsafe
/// for is a contradiction that would put it in a physiotherapy session for the
/// exact injury it aggravates.
library;

import '../../features/workouts/domain/exercise_tags.dart';

/// One row of the shipped exercise library.
class StarterExercise {
  const StarterExercise({
    required this.id,
    required this.name,
    required this.nameHe,
    required this.primaryMuscle,
    required this.primaryMuscleHe,
    required this.unit,
    required this.notes,
    required this.notesHe,
    this.equipment = const <Equipment>{},
    this.contraindicatedFor = const <BodyPart>{},
    this.rehabFor = const <BodyPart>{},
    required this.pattern,
    required this.mechanic,
    required this.loadClass,
  });

  final String id;
  final String name;
  final String nameHe;
  final String primaryMuscle;
  final String primaryMuscleHe;

  /// How a set is measured: `kg`, `bodyweight`, `band`, `minutes`.
  final String unit;
  final String notes;

  /// The Hebrew cue. Required, like [nameHe]: these are technique and safety
  /// instructions, and an exercise that shows Hebrew name over English cue is
  /// exactly the half-translated result the content-language work removed.
  final String notesHe;

  final Set<Equipment> equipment;

  /// Body parts this exercise is unsafe for.
  final Set<BodyPart> contraindicatedFor;

  /// Body parts this exercise actively helps rehabilitate. Never overlaps
  /// [contraindicatedFor] -- see the library note above.
  final Set<BodyPart> rehabFor;

  final MovementPattern pattern;
  final Mechanic mechanic;
  final LoadClass loadClass;

  /// Whether this is a physiotherapy movement rather than training work.
  bool get isRehab => primaryMuscle == 'Rehab';
}

